"""Business rules for the single entity: a loan.

Fields
  id             string (uuid, generated by the service)
  equipment_name string, required
  borrower_name  string, required
  loan_date      YYYY-MM-DD, required
  return_date    YYYY-MM-DD or null
  status         "borrowed" (default) or "returned"
  created_at / updated_at  ISO timestamps (UTC), set by the service
"""
import datetime
import uuid

STATUSES = ("borrowed", "returned")
UPDATABLE = ("equipment_name", "borrower_name", "loan_date", "return_date", "status")
MAX_TEXT = 100


class ValidationError(ValueError):
    """Raised when the request data is not acceptable (HTTP 400)."""


def _now():
    return datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds")


def _text(name, value):
    if not isinstance(value, str) or not value.strip():
        raise ValidationError(f"{name} must be a non-empty string")
    value = value.strip()
    if len(value) > MAX_TEXT:
        raise ValidationError(f"{name} must be at most {MAX_TEXT} characters")
    return value


def _date(name, value):
    if not isinstance(value, str):
        raise ValidationError(f"{name} must be a date in YYYY-MM-DD format")
    try:
        parsed = datetime.datetime.strptime(value, "%Y-%m-%d").date()
    except ValueError:
        raise ValidationError(f"{name} must be a date in YYYY-MM-DD format")
    return parsed.isoformat()


def _status(value):
    if value not in STATUSES:
        raise ValidationError("status must be 'borrowed' or 'returned'")
    return value


def build_new_loan(data):
    for field in ("equipment_name", "borrower_name", "loan_date"):
        if field not in data:
            raise ValidationError(f"{field} is required")
    now = _now()
    loan = {
        "id": str(uuid.uuid4()),
        "equipment_name": _text("equipment_name", data["equipment_name"]),
        "borrower_name": _text("borrower_name", data["borrower_name"]),
        "loan_date": _date("loan_date", data["loan_date"]),
        "return_date": None,
        "status": "borrowed",
        "created_at": now,
        "updated_at": now,
    }
    if data.get("return_date") is not None:
        loan["return_date"] = _date("return_date", data["return_date"])
    if "status" in data:
        loan["status"] = _status(data["status"])
    return loan


def apply_update(existing, data):
    changes = {k: data[k] for k in UPDATABLE if k in data}
    if not changes:
        raise ValidationError("no updatable fields in body (" + ", ".join(UPDATABLE) + ")")

    loan = dict(existing)
    if "equipment_name" in changes:
        loan["equipment_name"] = _text("equipment_name", changes["equipment_name"])
    if "borrower_name" in changes:
        loan["borrower_name"] = _text("borrower_name", changes["borrower_name"])
    if "loan_date" in changes:
        loan["loan_date"] = _date("loan_date", changes["loan_date"])
    if "return_date" in changes:
        value = changes["return_date"]
        loan["return_date"] = None if value is None else _date("return_date", value)
    if "status" in changes:
        loan["status"] = _status(changes["status"])

    # Returning an item without saying when: record today's date.
    if loan["status"] == "returned" and not loan.get("return_date"):
        loan["return_date"] = datetime.date.today().isoformat()

    loan["updated_at"] = _now()
    return loan
